fun tinhDienTich(chieuDai : Double , chieuRong : Double): Double {
    val dt = chieuDai * chieuRong
    return dt
}


println("Diện tích HCN: ${tinhDienTich(chieuDai = 10.0, chieuRong = 15.0)} m*2")
println("Diện tích HCN: ${tinhDienTich(chieuDai = 20.0, chieuRong = 25.0)} m*2")